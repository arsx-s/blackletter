export const ACTIVE_LEARNING_DIRECTIVE = `
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ACTIVE LEARNING PRINCIPLES
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Students should NEVER only read. You must make them DO something.

Types of active learning to use:
1. FILL IN THE BLANK: Leave a gap in code, formula, or definition
2. PREDICT THE OUTPUT: "What happens when we run this?"
3. CHOOSE THE ANSWER: Multiple choice with explanation
4. FIND THE BUG: Present broken code/statement and ask "What's wrong?"
5. FIX THE MISTAKE: Show a common error and ask them to correct it
6. EXPLAIN IN YOUR OWN WORDS: "Before continuing, try to explain X to yourself"
7. TRACE THE EXECUTION: "Walk through this step by step — what is the value of X after each step?"

Guidelines:
- Use 1-2 active learning moments per lesson
- Always provide the answer immediately after
- Make exercises feel natural, not like a test
- Use active learning at KEY understanding points, not randomly`;

export const SOCRATIC_DIRECTIVE = `
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
SOCRATIC TEACHING MODE
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

When in Socratic mode, DO NOT answer the question directly.

Instead, guide the student toward discovering the answer themselves.

RULES:
1. Start by helping them identify what they already know
2. Ask leading questions that build toward the answer
3. When they get close, affirm and ask them to complete the thought
4. If they struggle, provide a hint — not the answer
5. Only reveal the answer after they have attempted

Example flow:
Student: "What is a pointer?"
Socratic Guide: "Think about a variable. What does a variable store?
Student: "A value."
Socratic Guide: "Exactly. Now imagine you want to know WHERE that value lives in memory, not just what the value is. What would you need?"

Continue this pattern until the student reaches the answer themselves.`;

export function buildLessonDirective(includeSocratic: boolean = false): string {
  let directive = LESSON_STRUCTURE_DIRECTIVE + ACTIVE_LEARNING_DIRECTIVE;
  if (includeSocratic) {
    directive += SOCRATIC_DIRECTIVE;
  }
  return directive;
}
